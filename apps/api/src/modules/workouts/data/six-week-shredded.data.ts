export const SIX_WEEK_SHREDDED_ID = 'prog_6_week_shredded_12w';

export interface IProgramCycleWeek {
  weekNumber: number; // 1 to 12
  cycleNumber: 1 | 2; // 1 (Weeks 1-6) or 2 (Weeks 7-12)
  cycleSourceWeek: number; // 1 to 6
  days: ISixWeekShreddedDayPlan[];
}

export function build12WeekSchedule(): IProgramCycleWeek[] {
  const weeks: IProgramCycleWeek[] = [];
  for (let w = 1; w <= 12; w++) {
    const cycleNumber: 1 | 2 = w <= 6 ? 1 : 2;
    const cycleSourceWeek = w <= 6 ? w : w - 6;
    weeks.push({
      weekNumber: w,
      cycleNumber,
      cycleSourceWeek,
      // References the exact same canonical workout definitions!
      days: CANONICAL_6_WEEK_SPLIT,
    });
  }
  return weeks;
}

